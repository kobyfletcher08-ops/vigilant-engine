import {build as bundle} from 'esbuild';
import {build as client} from 'vite';
import {readFile,mkdir,copyFile,writeFile,rm} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),root=resolve('.'),stage=resolve('desktop-package');
const pkg=JSON.parse(await readFile('package.json','utf8'));
await rm(stage,{recursive:true,force:true});await mkdir(stage,{recursive:true});
await client({configFile:resolve('vite.desktop.config.ts')});
const anchor=require.resolve('@coral-xyz/anchor',{paths:[dirname(require.resolve('@pump-fun/pump-swap-sdk'))]});
await bundle({entryPoints:['desktop/backend.ts'],outfile:resolve(stage,'backend.cjs'),bundle:true,platform:'node',format:'cjs',target:'node22',minify:false,sourcemap:false,logLevel:'warning',alias:{'@coral-xyz/anchor':anchor},plugins:[{name:'local-desktop-auth',setup(build){build.onResolve({filter:/chatgpt-auth$/},()=>({path:resolve(root,'desktop/auth.ts')}));}}]});
for(const file of ['main.cjs','policy.cjs'])await copyFile('desktop/'+file,resolve(stage,file));
await writeFile(resolve(stage,'package.json'),JSON.stringify({name:'vigilant-engine-desktop',productName:'Vigilant Engine',version:pkg.version,description:'Local Solana, BSC and Arbitrum arbitrage console',author:'Koby Dench',main:'main.cjs',private:true,packageManager:'npm@11.9.0',dependencies:{}},null,2)+'\n');
console.log('Desktop interface and backend bundled together.');
